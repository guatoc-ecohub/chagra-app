import biopreparados from '../../catalog/biopreparados-seed.json';
import fichasBiopreparados from '../data/biopreparadosCatalogo.json';
import { resolveAgentScenario } from './agentScenario.js';

const norm = (s) => String(s || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
const bocashiSeed = biopreparados.biopreparados.find((item) => item.id === 'bocashi');
// RA3 2026-10-11 (R07): la respuesta citaba la semilla («Bajo riesgo») mientras
// la ficha que ve el usuario dice riesgo medio y advierte la gallinaza sin
// higienizar. Los cuidados y la clase de riesgo salen de la ficha.
const bocashiFicha = fichasBiopreparados.find((item) => item.id === 'bocashi');

const RIESGO_LEGIBLE = { bajo: 'riesgo bajo', medio: 'riesgo medio', alto: 'riesgo alto' };

// Quote the process and safety fields, without combining conflicting dose fields.
export function buildBocashiCatalogAnswer() {
  const ficha = bocashiFicha;
  if (!ficha?.proceso_resumen || !ficha.precaucion_seguridad || !ficha.source_ids?.length) return null;
  const riesgo = RIESGO_LEGIBLE[ficha.safety_class] || 'riesgo sin clasificar';
  const epp = Array.isArray(ficha.ppe_required) && ficha.ppe_required.length
    ? ` Protéjase con ${ficha.ppe_required.join(' y ')}.` : '';
  return {
    id: 'bocashi_catalogo',
    text: 'Para armarlo con lo que tiene, cuénteme dos cosas: ¿qué materiales tiene a mano (gallinaza o estiércol de vaca, cascarilla o paja, tierra, carbón, melaza o jugo de caña) y de qué tamaño quiere la tanda (unos sacos, una carretilla, varios quintales)? Con eso le ajusto las cantidades.\n\n' +
      'El bocashi es un abono orgánico sólido fermentado que se incorpora al suelo, no un preparado foliar. Según la ficha Bocashi del catálogo Chagra:\n\n' +
      `1. Reúna: ${(bocashiSeed?.ingredientes || []).join(', ')}. Las cantidades de una tanda están en la ficha.\n` +
      '2. Mezcle los materiales e incorpore el agua con la melaza y la levadura de forma uniforme.\n' +
      `3. Siga el proceso de la ficha: ${ficha.proceso_resumen}\n` +
      `4. Cuidados de la ficha (${riesgo}): ${ficha.precaucion_seguridad}${epp}\n\n` +
      'Ficha completa, con cantidades en sacos y en kilos: Biopreparados, Bocashi (chagra.app/#biopreparados).\n\n' +
      `Fuente: catálogo Chagra, ficha Bocashi, referencia ${ficha.source_ids.join(', ')}.` +
      (bocashiSeed?.fuente ? ` ${bocashiSeed.fuente.replace(/—/g, ',')}` : '') + '\n' +
      'La ficha aún tiene revisión pendiente. Sus campos de dosis difieren; no los combino ni doy una cantidad de aplicación sin validarla para su cultivo.',
    fuente: 'Catálogo Chagra, ficha Bocashi',
    catalog_answer: 'bocashi',
  };
}

// A catalogue badge cannot authorize an arbitrary recipe generated by a model.
export function isBocashiCatalogAnswer(message) {
  return message?.metadata?.catalog_answer === 'bocashi'
    && message.content === buildBocashiCatalogAnswer()?.text;
}

/**
 * @param {string} question
 * @returns {Promise<null|{id:string, text:string, fuente?:string, catalog_answer?:string, resolvedEntities?:any[]}>}
 */
export async function buildCatalogExtensionAnswer(question, { finca = null, profile = {} } = {}) {
  const q = norm(question);
  if (/\b(bocashi|bokashi)\b/.test(q) && /\b(que es|prepar\w*|hago|hacer|receta|pasos)\b/.test(q)) {
    return buildBocashiCatalogAnswer();
  }
  if (/\b(?:camping|acampar|campamento|carpa)\b/.test(q)
    && /\b(?:quebrada|rio|riachuelo|cauce|nacimiento)\b/.test(q)) {
    return {
      id: 'camping_ronda_hidrica',
      text: 'No acampe dentro de la ronda hídrica ni en la franja de protección delimitada para el cauce. Si el límite no está señalizado, confirme dónde termina antes de instalarse; no puedo fijar aquí una distancia. Evite fogatas, residuos, detergentes y compactar el suelo junto al agua.',
    };
  }

  if (!/\b(cafe|cafetal|cafeto)\b/.test(q)) return null;
  const { fincaAltitud } = resolveAgentScenario(question, profile, finca);
  const asksToPlant = /\b(?:siembro|sembrar|plantar|cultivar)\b/.test(q);
  if (asksToPlant && !/\b(?:sombra|sombrio)\b/.test(q) && fincaAltitud != null) {
    const { getSpeciesById } = await import('../db/catalogDB.js');
    const coffee = await getSpeciesById('coffea_arabica');
    const min = Number(coffee?.altitud_msnm?.min_absoluto);
    const max = Number(coffee?.altitud_msnm?.max_absoluto);
    if (Number.isFinite(min) && Number.isFinite(max) && (fincaAltitud < min || fincaAltitud > max)) {
      return {
        id: 'cafe_fuera_rango_catalogo',
        fuente: 'Catálogo Chagra, ficha de café',
        text: `No le recomiendo sembrar café en esta finca: el catálogo Chagra documenta el café arábica entre ${min} y ${max} msnm, y la finca está a ${fincaAltitud} msnm, fuera de ese rango. El catálogo no respalda sustituirlo por café robusta a esta altura. Es más seguro escoger un cultivo con rango documentado para la finca. Fuente: catálogo Chagra, ficha de café.`,
      };
    }
  }

  if (!/\b(sombra|sombrio)\b/.test(q)) return null;
  if (fincaAltitud == null) return { id: 'sombra_sin_altura', text: '¿En qué municipio y a qué altura está el café? Con esos datos puedo consultar las especies de sombra de ese piso térmico.' };
  const { getSpeciesById } = await import('../db/catalogDB.js');
  const [coffee, ...trees] = await Promise.all([
    getSpeciesById('coffea_arabica'), getSpeciesById('inga_densiflora'),
    getSpeciesById('cordia_alliodora'), getSpeciesById('musa_paradisiaca'),
  ]);
  const viable = trees.filter((tree) => tree && coffee?.companions?.includes(tree.id)
    && tree.altitud_msnm?.min_absoluto != null && tree.altitud_msnm?.max_absoluto != null
    && fincaAltitud >= tree.altitud_msnm.min_absoluto && fincaAltitud <= tree.altitud_msnm.max_absoluto);
  if (!viable.length) return { id: 'sombra_sin_ficha', text: 'No pude confirmar especies de sombra para esa altura en el catálogo local. Puede reintentar la consulta o revisarla con asistencia técnica.' };
  return {
    id: 'sombra_cafe_catalogo', catalog_answer: 'sombra_cafe', fuente: 'Catálogo Chagra, ficha de café y sus compañeras',
    // Exact catalogue IDs ground identity only; their validation level is preserved.
    resolvedEntities: [coffee, ...viable].map(species => ({
      ...species, canonical_id: species.id, mentioned: species.nombre_comun,
      kind: 'especie', confidence: 1,
    })),
    text: `Revise dónde necesita sombra y conserve la ventilación del cafetal.\n\nPara café a ${fincaAltitud} m, el catálogo Chagra registra estas compañeras dentro de su rango de altura:\n` +
      viable.map(tree => `- ${tree.nombre_comun} (${tree.nombre_cientifico}).${tree.id === 'musa_paradisiaca' ? ' Puede aportar sombra transitoria durante el establecimiento.' : ''}`).join('\n') +
      '\n\nEl sombrío se ajusta a radiación, agua y suelo; no hay un porcentaje universal. Confirme municipio y condiciones del lote para elegir y distribuir estas especies.\n\n' +
      `Fuente: catálogo Chagra, ficha café (Cenicafé, Manual del Cafetero 2013) y fichas ${viable.map(t => t.id).join(', ')}.`,
  };
}
